Add-BundleLine $bundleBuilder '	local ChunkFunction, CompileErrorString = CompileSourceString(WrappedSourceString, "@" .. SegmentTable.path)'
Add-BundleLine $bundleBuilder '	if type(ChunkFunction) ~= "function" then'
