    }
    Add-BundleLine $bundleBuilder "		},"
    Add-BundleLine $bundleBuilder ('		source = ' + (ConvertTo-LuaLongStringLiteral $segmentMetadata.SourceText) + ",")
    Add-BundleLine $bundleBuilder "	},"
}

Add-BundleLine $bundleBuilder "}"
